/** Calendar date parts in Asia/Manila (PHT, UTC+8). */
function manilaParts(now: Date) {
  const p = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Manila", year: "numeric", month: "2-digit", day: "2-digit" }).formatToParts(now);
  const g = (t: string) => Number(p.find((x) => x.type === t)!.value);
  return { y: g("year"), m: g("month"), d: g("day") };
}

export function manilaDayOfYear(now = new Date()) {
  const { y, m, d } = manilaParts(now);
  return Math.round((Date.UTC(y, m - 1, d) - Date.UTC(y, 0, 0)) / 86_400_000);
}

export function manilaDateKey(now = new Date()) {
  const { y, m, d } = manilaParts(now);
  return `${y}-${m}-${d}`;
}

export function devotionForToday(now = new Date()): Devotion {
  return DEVOTIONS[manilaDayOfYear(now) % DEVOTIONS.length];
}

/** Milliseconds until the next 12:00 midnight in Manila (UTC+8, no DST). */
export function msUntilManilaMidnight(now = new Date()) {
  const shifted = now.getTime() + 8 * 3_600_000;
  return 86_400_000 - (shifted % 86_400_000) + 500;
}
